-- NAVE V5: Shared fictional journey, isolated from production ride, WhatsApp and payment tables.
-- DRAFT ONLY. Do not apply to the shared Supabase project without explicit approval.
-- Requires existing public.nave_is_admin(), auth.uid(), auth.jwt() from NAVE admin infrastructure.
-- Only the NAVE administrator with AAL2 can open two separate authenticated demo browser sessions.
-- Demo role labels ("passenger", "driver") are UI roles, NOT actual passenger/driver credentials.
create table if not exists public.nave_v5_lab_sessions (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null,
  creation_key uuid not null,
  category_code text not null check(category_code in ('eco','confort','executive','navegator')),
  scenario text not null check(scenario in ('normal','first_busy','no_route')),
  phase text not null check(phase in ('offer_pending','driver_to_pickup','at_pickup','in_trip','completed','cancelled','no_driver')),
  driver_code text check(driver_code is null or driver_code in ('DEMO-ALFA','DEMO-BETA')),
  declined text[] not null default '{}'::text[],
  fare_cents integer not null check(fare_cents between 0 and 100000),
  version integer not null default 1 check(version between 1 and 8),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  expires_at timestamptz not null default (now()+interval '30 minutes'),
  unique(owner_id,creation_key)
);
create index if not exists nave_v5_lab_sessions_expire_idx
 on public.nave_v5_lab_sessions(expires_at);

create table if not exists public.nave_v5_lab_events (
 id bigint generated by default as identity primary key,
 session_id uuid not null references public.nave_v5_lab_sessions(id) on delete cascade,
 request_id uuid not null,
 version integer not null,
 event text not null check(event in ('start','accept','decline','arrive','board','complete','cancel')),
 actor text not null check(actor in ('passenger','driver')),
 created_at timestamptz not null default now(),
 unique(session_id,request_id),
 unique(session_id,version)
);
alter table public.nave_v5_lab_sessions enable row level security;
alter table public.nave_v5_lab_events enable row level security;
revoke all on public.nave_v5_lab_sessions from public, anon, authenticated;
revoke all on public.nave_v5_lab_events from public, anon, authenticated;
revoke all on sequence public.nave_v5_lab_events_id_seq from public, anon, authenticated;

create or replace function public.nave_v5_lab_snapshot(p_id uuid)
returns jsonb language plpgsql stable security definer set search_path='' as $lab$
declare v public.nave_v5_lab_sessions%rowtype;
begin
 if auth.uid() is null or coalesce(auth.jwt()->>'aal','') <> 'aal2' or
    not public.nave_is_admin() then return null; end if;
 select * into v from public.nave_v5_lab_sessions
 where id=p_id and owner_id=auth.uid() and expires_at>now();
 if not found then return null; end if;
 return jsonb_build_object(
   'id',v.id,'version',v.version,'phase',v.phase,'categoryCode',v.category_code,
   'scenario',v.scenario,'driverCode',v.driver_code,'declined',to_jsonb(v.declined),
   'fareCents',v.fare_cents,'expiresAt',v.expires_at,
   'testOnly',true,'simulation',true,'persistenceEnabled',true,
   'commercialRidesEnabled',false,'whatsappSendEnabled',false,'paymentsEnabled',false,
   'realGpsUsed',false,'externalRoutingEnabled',false,
   'driverAuthenticationReady',false,'source','isolated-admin-lab',
   'notice','Sessao ficticia: ambos navegadores usam a conta administrativa com MFA. Nada de corridas, GPS ou mensagens reais.'
 );
end $lab$;

create or replace function public.nave_v5_lab_start(
 p_category text, p_scenario text, p_creation_key uuid
) returns jsonb language plpgsql volatile security definer set search_path='' as $lab$
declare v_owner uuid; v_id uuid; v_driver text; v_phase text; v_fare integer;
begin
 v_owner := auth.uid();
 if v_owner is null or coalesce(auth.jwt()->>'aal','') <> 'aal2' or
    not public.nave_is_admin() then return null; end if;
 if p_creation_key is null or p_category is null or p_scenario is null or
    p_category not in ('eco','confort','executive','navegator') or
    p_scenario not in ('normal','first_busy','no_route') then return null; end if;
 select id into v_id from public.nave_v5_lab_sessions
 where owner_id=v_owner and creation_key=p_creation_key;
 if found then return public.nave_v5_lab_snapshot(v_id); end if;

 -- At most 10 active lab sessions per owner; expiry is 30 min, with cron purge later.
 if (select count(*) from public.nave_v5_lab_sessions where owner_id=v_owner
      and expires_at>now() and phase not in ('completed','cancelled','no_driver'))>=10
 then return null; end if;
 v_driver := case
  when p_scenario='no_route' then null
  when p_scenario='first_busy' and p_category in ('eco','confort') then 'DEMO-ALFA'
  when p_scenario='first_busy' then null
  else 'DEMO-BETA' end;
 v_phase := case when v_driver is null then 'no_driver' else 'offer_pending' end;
 v_fare := round((case p_category
    when 'eco' then 350+4300*0.165+720/60.0*20
    when 'confort' then 440+4300*0.195+720/60.0*22
    when 'executive' then 640+4300*0.310+720/60.0*48
    else 720+4300*0.340+720/60.0*55 end)::numeric)::integer;
 insert into public.nave_v5_lab_sessions
  (owner_id,creation_key,category_code,scenario,phase,driver_code,fare_cents)
 values(v_owner,p_creation_key,p_category,p_scenario,v_phase,v_driver,v_fare)
 on conflict(owner_id,creation_key) do nothing
 returning id into v_id;
 if v_id is null then
  select id into v_id from public.nave_v5_lab_sessions
   where owner_id=v_owner and creation_key=p_creation_key;
 end if;
 if v_id is null then return null; end if;
 insert into public.nave_v5_lab_events(session_id,request_id,version,event,actor)
 values(v_id,p_creation_key,1,'start','passenger')
 on conflict(session_id,request_id) do nothing;
 return public.nave_v5_lab_snapshot(v_id);
end $lab$;

create or replace function public.nave_v5_lab_advance(
 p_id uuid,p_expected_version integer,p_action_key uuid,p_action text,p_actor text
) returns jsonb language plpgsql volatile security definer set search_path='' as $lab$
declare v public.nave_v5_lab_sessions%rowtype; v_next text; v_driver text; v_declined text[];
begin
 if auth.uid() is null or coalesce(auth.jwt()->>'aal','') <> 'aal2' or
   not public.nave_is_admin() then return null; end if;
 if p_id is null or p_action_key is null or p_action is null or
    p_action not in ('accept','decline','arrive','board','complete','cancel') or
    p_actor is null or p_actor not in ('passenger','driver') or
    (p_action='cancel' and p_actor<>'passenger') or
    (p_action<>'cancel' and p_actor<>'driver')
 then return null; end if;

 select * into v from public.nave_v5_lab_sessions
 where id=p_id and owner_id=auth.uid() and expires_at>now()
 for update;
 if not found then return null; end if;
 -- Same idempotency key never applies a transition twice, even if client retries.
 if exists(select 1 from public.nave_v5_lab_events
  where session_id=v.id and request_id=p_action_key)
 then return public.nave_v5_lab_snapshot(v.id); end if;
 if p_expected_version is null or v.version<>p_expected_version then
  return jsonb_build_object('error','version_conflict','current',public.nave_v5_lab_snapshot(v.id));
 end if;
 if v.version>=8 then return null; end if;
 v_next:=v.phase;v_driver:=v.driver_code;v_declined:=v.declined;

 if p_action='accept' and v.phase='offer_pending' then v_next:='driver_to_pickup';
 elsif p_action='decline' and v.phase='offer_pending' then
  v_declined:=array_append(v.declined,v.driver_code);
  if v.driver_code='DEMO-BETA' and v.category_code in ('eco','confort')
     and v.scenario='normal' then
    v_driver:='DEMO-ALFA';v_next:='offer_pending';
  else v_driver:=null;v_next:='no_driver';end if;
 elsif p_action='arrive' and v.phase='driver_to_pickup' then v_next:='at_pickup';
 elsif p_action='board' and v.phase='at_pickup' then v_next:='in_trip';
 elsif p_action='complete' and v.phase='in_trip' then v_next:='completed';
 elsif p_action='cancel' and v.phase in ('offer_pending','driver_to_pickup','at_pickup') then
  v_next:='cancelled';
 else return null; end if;

 update public.nave_v5_lab_sessions set phase=v_next,driver_code=v_driver,
  declined=v_declined,version=v.version+1,updated_at=now()
 where id=v.id;
 insert into public.nave_v5_lab_events(session_id,request_id,version,event,actor)
 values(v.id,p_action_key,v.version+1,p_action,p_actor);
 return public.nave_v5_lab_snapshot(v.id);
end $lab$;

revoke all on function public.nave_v5_lab_snapshot(uuid) from public,anon,authenticated;
revoke all on function public.nave_v5_lab_start(text,text,uuid) from public,anon,authenticated;
revoke all on function public.nave_v5_lab_advance(uuid,integer,uuid,text,text) from public,anon,authenticated;
grant execute on function public.nave_v5_lab_snapshot(uuid) to authenticated;
grant execute on function public.nave_v5_lab_start(text,text,uuid) to authenticated;
grant execute on function public.nave_v5_lab_advance(uuid,integer,uuid,text,text) to authenticated;
comment on table public.nave_v5_lab_sessions is 'Isolated NAVE V5 administrator-only test session. No rides, payments, phone, driver GPS, or WhatsApp data.';
